/* bake_brain.js — turn a trained champion into the default_brain.js the page loads.
 *
 *   node bake_brain.js                          training/champion.json -> default_brain.js
 *   node bake_brain.js training/run2_champ.json
 *
 * Refuses to bake a brain whose corpus hash or embedding width does not match
 * the current task bank. A brain evolved against different sentences still
 * *runs* — the vectors are the same shape — it just quietly means something
 * else by every input, and that is the kind of mismatch that costs an evening.
 */
"use strict";

const fs = require("fs");
const path = require("path");
const { loadSim } = require("./simload.js");
loadSim(__dirname);

const src = process.argv[2] || path.join("training", "champion.json");
const p = path.isAbsolute(src) ? src : path.join(__dirname, src);
if (!fs.existsSync(p)) {
    console.error(`no champion at ${src}. Train one first:  node train.js --gens 400`);
    process.exit(1);
}
const saved = JSON.parse(fs.readFileSync(p, "utf8"));

/* A MISSING PROVENANCE FIELD IS NOT A PASSING CHECK.
 *
 * Each guard below is written as "if the brain declares X and X is wrong,
 * refuse". That is correct for a brain that declares things and useless for one
 * that does not — an undeclared corpus hash skipped the comparison entirely and
 * baked, printing "corpus undefined" in a header nobody reads. Say so instead. */
const undeclared = ["corpusHash", "embDim", "embModel"].filter(k => saved[k] === undefined);
if (undeclared.length) {
    console.error(`! ${path.basename(src)} declares no ${undeclared.join(", ")} — ` +
        `the compatibility checks below cannot run on it.`);
    if (!process.argv.includes("--force")) {
        console.error(`  Re-save it with those fields, or pass --force if you are certain the ` +
            `brain was fitted against the current tasks.js and embedder.`);
        process.exit(1);
    }
    console.error(`  --force given: baking anyway, provenance unverified.`);
}

const want = corpusHash();
if (saved.corpusHash && saved.corpusHash !== want) {
    console.error(`corpus mismatch: brain was evolved against ${saved.corpusHash}, the bank is now ${want}.`);
    console.error(`Either re-train, or check out the tasks.js the brain was trained on.`);
    process.exit(1);
}
if (saved.embDim && saved.embDim !== Embedding.dim) {
    console.error(`embedding width mismatch: brain expects ${saved.embDim}, task_embeddings.js provides ${Embedding.dim}.`);
    process.exit(1);
}
if (saved.embModel && Embedding.meta && saved.embModel !== Embedding.meta.model) {
    console.error(`embedder mismatch: brain was evolved on ${saved.embModel}, the bake is ${Embedding.meta.model}.`);
    process.exit(1);
}

// sanity: the brain must actually load and produce finite output
const brain = Brain.fromJSON(saved.brain);
const out = brain.act(new Float32Array(MOTOR_FEATS).fill(0.1));
for (let i = 0; i < 5; i++) if (!Number.isFinite(out[i])) {
    console.error("champion produces non-finite output — refusing to bake");
    process.exit(1);
}

/* PROVENANCE IS CODE, NOT A COMMENT.
 *
 * This file used to stamp every bake with a fixed "evolved — no gradients"
 * header. That was true of every brain it had ever seen, and became false the
 * moment one arrived from distill.js — at which point the page would have
 * carried a confident, wrong claim about how it was made. Whatever produced the
 * brain writes a `lineage` string into the champion file and it is carried
 * through here unaltered; a brain that does not say so gets called out rather
 * than given the benefit of the doubt. */
const lineage = saved.lineage || "unrecorded — the champion file carries no lineage field";
const payload = {
    gen: saved.gen, fitness: saved.fitness, championGen: saved.championGen,
    stage: saved.stage, embDim: saved.embDim, embModel: saved.embModel,
    corpusHash: saved.corpusHash, lineage,
    heldOut: saved.heldOut, brain: saved.brain
};
const outPath = path.join(__dirname, "default_brain.js");
fs.writeFileSync(outPath,
    `/* default_brain.js — GENERATED by bake_brain.js from ${path.basename(src)}. Do not edit.\n` +
    ` * gen ${saved.gen}, fitness ${Math.round(saved.fitness || 0)}, embedder ${saved.embModel}, corpus ${saved.corpusHash}\n` +
    ` * lineage: ${lineage}\n` +
    (saved.heldOut ? ` * held-out phrasings: ${(100 * saved.heldOut.balls).toFixed(1)}% balls, ${(100 * saved.heldOut.tasks).toFixed(1)}% tasks\n` : "") +
    ` */\n"use strict";\nconst DEFAULT_BRAIN = ${JSON.stringify(payload)};\n` +
    `if (typeof module !== "undefined") module.exports = { DEFAULT_BRAIN };\n`);

console.log(`baked default_brain.js — gen ${saved.gen}, fitness ${Math.round(saved.fitness || 0)}, ` +
    `${(fs.statSync(outPath).size / 1024).toFixed(0)} kB`);
console.log(`lineage: ${lineage}`);
