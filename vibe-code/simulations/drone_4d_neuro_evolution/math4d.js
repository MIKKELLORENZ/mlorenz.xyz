/* math4d.js — the rotational algebra of four-dimensional space.
 *
 * In 3D you can be sloppy: an angular velocity is "a vector", a torque is "a
 * vector", and the cross product ties them together. None of that survives the
 * step to 4D, and pretending it does is the fastest way to build a simulator
 * that looks plausible and is wrong. The honest objects are:
 *
 *   ORIENTATION   R ∈ SO(4) — a 4×4 matrix, columns = body axes in world
 *                 coordinates. There is no quaternion here; unit quaternions
 *                 double-cover SO(3), not SO(4). (SO(4) is double-covered by
 *                 S³×S³ — a *pair* of quaternions — which is a fine
 *                 representation but buys nothing over a matrix.)
 *
 *   ANGULAR       Ω, a 4×4 antisymmetric matrix — equivalently a BIVECTOR with
 *   VELOCITY      C(4,2) = 6 independent components, one per coordinate plane.
 *                 Rotation in 4D happens in a PLANE, not about an axis. The
 *                 "axis of rotation" is a 3D accident: the orthogonal
 *                 complement of a plane is only 1-dimensional when n = 3.
 *
 *   ANGULAR       L, also antisymmetric, also 6 components.
 *   MOMENTUM
 *
 *   INERTIA       NOT a 4×4 matrix and NOT six independent numbers you may
 *                 pick freely. For a mass distribution with quadrupole
 *                 J = Σ m x xᵀ (a genuine 4×4 matrix), the map Ω ↦ L is
 *
 *                     L = J·Ω + Ω·J
 *
 *                 With J diagonal this collapses to a per-plane scalar,
 *                 L[b][a] = (J_a + J_b)·Ω[b][a], so the six planes have six
 *                 moments of inertia — but they are generated by only four
 *                 numbers and must satisfy the resulting consistency
 *                 conditions. drone4d.js exploits this (see PLANE_I).
 *
 * SIGN CONVENTIONS, fixed once and used everywhere:
 *
 *   Ω is defined by  v̇ = Ω·v  for a vector rigidly attached to the body.
 *   For a rotation in the plane (a,b) at rate ω, e_a turns toward e_b, so
 *       Ω[b][a] = +ω,   Ω[a][b] = −ω.
 *
 *   L = Σ m (v xᵀ − x vᵀ)         (note the order — see below)
 *   τ = Σ   (F xᵀ − x Fᵀ)
 *
 *   The commoner wedge convention x∧v gives L = −(JΩ + ΩJ), i.e. a sign flip
 *   against Ω. Taking v xᵀ − x vᵀ instead makes L = +(JΩ + ΩJ) and lines the
 *   whole system up: a positive Ω component means a positive L component in
 *   the same plane. Both conventions are correct; mixing them is not, and the
 *   mixture is invisible until the drone rotates the wrong way under torque.
 *   test_math.js pins this down numerically.
 *
 *   Ṙ = R·Ω  (Ω in the BODY frame), and Euler's equation in 4D is
 *
 *       L̇_body = τ_body − [Ω, L]        [Ω,L] = ΩL − LΩ
 *
 *   which is derived, not asserted: differentiate L_space = R L_body Rᵀ,
 *   substitute Ṙ = RΩ, and set the result equal to τ_space = R τ_body Rᵀ.
 *   In 3D the commutator [Ω,L] is exactly the familiar ω × (Iω) gyroscopic
 *   term; here it keeps that job with three extra planes to couple.
 *
 * The 4D analogue of "yaw is harmless, pitch and roll are not" falls straight
 * out of this basis: rotations in the three planes that CONTAIN the thrust
 * axis tip the drone over, and rotations in the three planes ORTHOGONAL to it
 * leave the thrust axis exactly where it was. See PLANES below.
 */
"use strict";

/* Body axis indices, used by every file in this project.
 *   0  R  right      1  U  up (the thrust axis)
 *   2  F  forward    3  A  ana (the fourth direction)
 * "Ana" and "kata" are Hinton's names for the two directions along the fourth
 * axis, in the same way "up"/"down" name the third. */
const AX_R = 0, AX_U = 1, AX_F = 2, AX_A = 3;

/* The six coordinate planes, in a fixed order. Planes 0,3,4 contain the
 * thrust axis U and are the TILT planes — rotating in one of them points the
 * thrust somewhere other than up, and the drone falls. Planes 1,2,5 live
 * entirely inside the 3-space orthogonal to U; rotating in them spins the
 * airframe without disturbing the thrust direction at all. Those three are the
 * exact 4D generalisation of yaw, and like yaw they are only weakly actuated
 * (rotor reaction torque), which is fine precisely because they are benign. */
const PLANES = [
    [AX_R, AX_U],   // 0  tilt   (right–up)
    [AX_R, AX_F],   // 1  heading (right–forward)   ← 3D's yaw plane
    [AX_R, AX_A],   // 2  heading (right–ana)
    [AX_U, AX_F],   // 3  tilt   (up–forward)
    [AX_U, AX_A],   // 4  tilt   (up–ana)
    [AX_F, AX_A]    // 5  heading (forward–ana)
];
const N_PLANES = 6;
/* true where the plane contains the thrust axis */
const PLANE_IS_TILT = PLANES.map(p => p[0] === AX_U || p[1] === AX_U);

/* ---------------------------------------------------------------- 4-vectors */
function v4(x, y, z, w) { return new Float64Array([x || 0, y || 0, z || 0, w || 0]); }
function v4norm(v) { return Math.sqrt(v[0] * v[0] + v[1] * v[1] + v[2] * v[2] + v[3] * v[3]); }
function v4dot(a, b) { return a[0] * b[0] + a[1] * b[1] + a[2] * b[2] + a[3] * b[3]; }
function v4dist(a, b) {
    const dx = a[0] - b[0], dy = a[1] - b[1], dz = a[2] - b[2], dw = a[3] - b[3];
    return Math.sqrt(dx * dx + dy * dy + dz * dz + dw * dw);
}

/* ---------------------------------------------------- 4×4 matrices (row-major)
 * m[r * 4 + c]. Vectors are columns: (M v)_r = Σ_c m[r*4+c] v_c. */
function m4identity(out) {
    const m = out || new Float64Array(16);
    m.fill(0); m[0] = m[5] = m[10] = m[15] = 1;
    return m;
}
function m4mul(a, b, out) {
    const m = out || new Float64Array(16);
    for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) {
            let s = 0;
            for (let k = 0; k < 4; k++) s += a[r * 4 + k] * b[k * 4 + c];
            m[r * 4 + c] = s;
        }
    }
    return m;
}
/* world = R · body */
function m4apply(m, v, out) {
    const o = out || new Float64Array(4);
    const v0 = v[0], v1 = v[1], v2 = v[2], v3 = v[3];
    for (let r = 0; r < 4; r++) {
        o[r] = m[r * 4] * v0 + m[r * 4 + 1] * v1 + m[r * 4 + 2] * v2 + m[r * 4 + 3] * v3;
    }
    return o;
}
/* body = Rᵀ · world  (R orthogonal, so the transpose IS the inverse) */
function m4applyT(m, v, out) {
    const o = out || new Float64Array(4);
    const v0 = v[0], v1 = v[1], v2 = v[2], v3 = v[3];
    for (let c = 0; c < 4; c++) {
        o[c] = m[c] * v0 + m[4 + c] * v1 + m[8 + c] * v2 + m[12 + c] * v3;
    }
    return o;
}
/* column j of R = body axis j expressed in world coordinates */
function m4col(m, j, out) {
    const o = out || new Float64Array(4);
    o[0] = m[j]; o[1] = m[4 + j]; o[2] = m[8 + j]; o[3] = m[12 + j];
    return o;
}

/* ------------------------------------------------- bivectors ⇄ antisymmetric
 * A bivector is 6 numbers, one per entry of PLANES. */
function bivToMat(b, out) {
    const m = out || new Float64Array(16);
    m.fill(0);
    for (let k = 0; k < N_PLANES; k++) {
        const a = PLANES[k][0], c = PLANES[k][1], v = b[k];
        m[c * 4 + a] = v;      // Ω[b][a] = +ω
        m[a * 4 + c] = -v;
    }
    return m;
}
function matToBiv(m, out) {
    const b = out || new Float64Array(N_PLANES);
    for (let k = 0; k < N_PLANES; k++) b[k] = m[PLANES[k][1] * 4 + PLANES[k][0]];
    return b;
}

/* τ = F xᵀ − x Fᵀ  — the torque of force F applied at body point x, as a
 * bivector. Reduces to the familiar x × F in 3D, with the same handedness. */
function torqueBiv(x, F, out) {
    const b = out || new Float64Array(N_PLANES);
    for (let k = 0; k < N_PLANES; k++) {
        const a = PLANES[k][0], c = PLANES[k][1];
        b[k] = F[c] * x[a] - x[c] * F[a];
    }
    return b;
}

/* The gyroscopic term [Ω,L] = ΩL − LΩ, bivector in → bivector out.
 * Written out on the 6 components rather than doing two 4×4 products: this
 * runs at 120 Hz for every drone in the population, and the commutator of two
 * antisymmetric matrices is itself antisymmetric, so 5/8 of the matrix work is
 * structurally redundant. Component k of the result, plane (a,c):
 *     (ΩL − LΩ)[c][a] = Σ_j Ω[c][j] L[j][a] − L[c][j] Ω[j][a]
 * with both matrices read out of their bivector form. */
const _cm1 = new Float64Array(16), _cm2 = new Float64Array(16), _cm3 = new Float64Array(16);
function commutatorBiv(omega, L, out) {
    const O = bivToMat(omega, _cm1), M = bivToMat(L, _cm2), C = _cm3;
    for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) {
            let s = 0;
            for (let k = 0; k < 4; k++) s += O[r * 4 + k] * M[k * 4 + c] - M[r * 4 + k] * O[k * 4 + c];
            C[r * 4 + c] = s;
        }
    }
    return matToBiv(C, out);
}

/* ------------------------------------------------------- staying inside SO(4)
 * Cayley transform: for antisymmetric A, cay(A) = (I − A)⁻¹(I + A) is EXACTLY
 * orthogonal with determinant +1, for any A — not orthogonal to first order,
 * exactly orthogonal. (I − A) is always invertible because the eigenvalues of a
 * real antisymmetric matrix are ±iθ, so 1 − λ never vanishes.
 *
 * cay(A) agrees with exp(A) to second order in A, which at dt = 1/120 s and
 * |Ω| ≲ 10 rad/s means |A| ≲ 0.04 and a per-step angle error under 3·10⁻⁵ rad.
 * The alternative — a truncated exponential series plus Gram–Schmidt — costs
 * about the same and is only approximately orthogonal before the fix-up, so
 * the drift it accumulates is real rotation error rather than a rounding
 * artefact. Gram–Schmidt still runs, but only against float64 round-off. */
function cayley(A, out) {
    /* Solve (I − A) X = (I + A) by Gauss–Jordan on a 4×8 augmented matrix. */
    const aug = new Float64Array(32);
    for (let r = 0; r < 4; r++) {
        for (let c = 0; c < 4; c++) {
            aug[r * 8 + c] = (r === c ? 1 : 0) - A[r * 4 + c];
            aug[r * 8 + 4 + c] = (r === c ? 1 : 0) + A[r * 4 + c];
        }
    }
    for (let col = 0; col < 4; col++) {
        let piv = col, bestv = Math.abs(aug[col * 8 + col]);
        for (let r = col + 1; r < 4; r++) {
            const v = Math.abs(aug[r * 8 + col]);
            if (v > bestv) { bestv = v; piv = r; }
        }
        if (piv !== col) {
            for (let c = 0; c < 8; c++) {
                const t = aug[col * 8 + c]; aug[col * 8 + c] = aug[piv * 8 + c]; aug[piv * 8 + c] = t;
            }
        }
        const d = aug[col * 8 + col] || 1e-300;
        for (let c = 0; c < 8; c++) aug[col * 8 + c] /= d;
        for (let r = 0; r < 4; r++) {
            if (r === col) continue;
            const f = aug[r * 8 + col];
            if (f === 0) continue;
            for (let c = 0; c < 8; c++) aug[r * 8 + c] -= f * aug[col * 8 + c];
        }
    }
    const m = out || new Float64Array(16);
    for (let r = 0; r < 4; r++) for (let c = 0; c < 4; c++) m[r * 4 + c] = aug[r * 8 + 4 + c];
    return m;
}

/* Modified Gram–Schmidt on the COLUMNS of R (the body axes). Pure hygiene
 * against float64 drift over a 10⁵-step episode; cayley() keeps the error at
 * the 10⁻¹⁶ level per step on its own. */
function orthonormalize(R) {
    for (let j = 0; j < 4; j++) {
        for (let i = 0; i < j; i++) {
            let d = 0;
            for (let r = 0; r < 4; r++) d += R[r * 4 + i] * R[r * 4 + j];
            for (let r = 0; r < 4; r++) R[r * 4 + j] -= d * R[r * 4 + i];
        }
        let n = 0;
        for (let r = 0; r < 4; r++) n += R[r * 4 + j] * R[r * 4 + j];
        n = Math.sqrt(n) || 1;
        for (let r = 0; r < 4; r++) R[r * 4 + j] /= n;
    }
    return R;
}

/* R ← R · cay(Ω·dt/2). Ω is a body-frame bivector, so the update is on the
 * RIGHT: body-frame rates compose in the body frame. */
const _iA = new Float64Array(16), _iC = new Float64Array(16), _iR = new Float64Array(16);
function integrateR(R, omega, dt) {
    const h = dt * 0.5;
    const A = _iA;
    A.fill(0);
    for (let k = 0; k < N_PLANES; k++) {
        const a = PLANES[k][0], c = PLANES[k][1], v = omega[k] * h;
        A[c * 4 + a] = v; A[a * 4 + c] = -v;
    }
    cayley(A, _iC);
    m4mul(R, _iC, _iR);
    R.set(_iR);
    orthonormalize(R);
    return R;
}

/* A simple rotation of `angle` radians in the coordinate plane (a,b). Used for
 * initial attitudes and by the viewer's 4D camera. */
function rotationInPlane(a, b, angle, out) {
    const m = m4identity(out);
    const c = Math.cos(angle), s = Math.sin(angle);
    m[a * 4 + a] = c; m[b * 4 + b] = c;
    m[b * 4 + a] = s; m[a * 4 + b] = -s;
    return m;
}

