/* bake.js — freeze a checkpoint's champion into champion.js for the browser.
 *
 *   node bake.js training/ckpt_main.json
 *
 * Weights go out as plain numbers rounded to 6 significant figures. Float32
 * carries about 7, so the rounding is below the precision the trainer itself
 * kept, and it shrinks the file by roughly half. The sha1 of the exact weights
 * is recorded so a brain in the browser can be matched back to the run that
 * produced it — the 3D project learned to care about that after two "improved"
 * checkpoints turned out to hold byte-identical nets.
 */
"use strict";
require("./bootstrap.js");
const fs = require("fs");
const path = require("path");
const crypto = require("crypto");

const ckPath = process.argv[2] || "training/ckpt_main.json";
const ck = JSON.parse(fs.readFileSync(ckPath, "utf8"));
if (!ck.champion) { console.error("no champion in " + ckPath); process.exit(1); }

const net = Net.fromJSON(ck.champion);
const h = crypto.createHash("sha1");
for (const w of net.weights) h.update(Buffer.from(w.buffer, w.byteOffset, w.byteLength));
const sha = h.digest("hex").slice(0, 12);

const round = (v) => Number(v.toPrecision(6));
const body = {
    sizes: net.sizes,
    weights: net.weights.map(w => Array.from(w, round))
};

const out = `/* champion.js — GENERATED by bake.js. Do not edit by hand.
 *
 * The evolved 4D flight controller: ${net.sizes.join(" → ")}
 *   source      ${path.basename(ckPath)}
 *   generation  ${ck.gen}
 *   weights     sha1 ${sha}
 *   parameters  ${net.weights.reduce((a, w) => a + w.length, 0)}
 *
 * Bred by mutation and selection only — there is no gradient descent anywhere
 * in this project. Held-out scores are in README.md; the training log's own
 * "best" column is not a measure of ability and should not be quoted as one.
 */
const CHAMPION = ${JSON.stringify(body)};
const CHAMPION_META = ${JSON.stringify({ gen: ck.gen, sha, source: path.basename(ckPath) })};
`;
const dest = path.join(__dirname, "champion.js");
fs.writeFileSync(dest, out);
console.log(`baked gen ${ck.gen} champion (sha1 ${sha}, ` +
    `${net.weights.reduce((a, w) => a + w.length, 0)} params) → champion.js ` +
    `[${(out.length / 1024).toFixed(0)} kB]`);
