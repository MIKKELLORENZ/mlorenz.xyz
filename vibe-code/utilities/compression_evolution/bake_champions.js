#!/usr/bin/env node
/* bake_champions.js — turns the records in training/*.json (written by
   train_headless.js) into champions.js, which the page replays ("Replay a recorded
   run") and uses to start single-file runs from the generalist when the browser has
   no run of its own yet.

   Nothing is taken on trust: every recorded champion is compressed again here on
   every whole file of its dataset, decompressed, compared byte for byte, and its score
   must equal what the trainer recorded. A record that fails is left out.

     node bake_champions.js            bake everything found in training/
     node bake_champions.js all cat    only these */
'use strict';
const fs = require('fs'), path = require('path');
const CE = require('./codec.js');
require('./analyze.js'); require('./genome.js'); require('./evolution.js'); require('./pool.js'); require('./run.js');
const { loadDataset, META } = require('./corpus_node.js');

const want = process.argv.slice(2), out = {}, dir = path.join(__dirname, 'training');
for (const id of ['all'].concat(META.map(m => m.id))) {
    if (want.length && !want.includes(id)) continue;
    const file = path.join(dir, id + '.json');
    if (!fs.existsSync(file)) { console.log(id.padEnd(8) + 'no record'); continue; }
    const rec = JSON.parse(fs.readFileSync(file, 'utf8'));
    if (!rec.genome) { console.log(id.padEnd(8) + 'record has no champion'); continue; }
    const ds = loadDataset(id, CE.analyze.analyze), t0 = Date.now(), sizes = [];
    let same = true;
    for (const p of ds.parts) {
        const r = CE.codec.compress(p.data, rec.genome, { shape: CE.analyze.shapeOf(p.info) }), back = CE.codec.decompress(r.bytes);
        same = same && back.length === p.data.length && back.every((v, i) => v === p.data[i]);
        sizes.push(r.size);
    }
    const score = ds.parts.length === 1 ? sizes[0] : Math.round(1e6 * sizes.reduce((a, v, i) => a + v / ds.parts[i].data.length, 0) / ds.parts.length);
    if (!same || score !== rec.size) { console.log(id.padEnd(8) + 'REJECTED: ' + (same ? 'score ' + score + ' ≠ recorded ' + rec.size : 'round trip failed')); continue; }
    const nominal = ds.parts.length === 1 ? ds.parts[0].data.length : 1e6, pct = 100 * score / nominal, refs = CE.Run.baselines(ds.parts);
    console.log(id.padEnd(8) + pct.toFixed(2).padStart(6) + '%  verified in ' + ((Date.now() - t0) / 1000).toFixed(1) + ' s · ' + rec.gens + ' generations, ' + rec.evals + ' designs, ' + rec.minutes + ' min · ahead of ' + refs.filter(b => b.pct > pct).length + '/' + refs.length + ' reference lines · ' + CE.genome.shortName(rec.genome));
    if (ds.parts.length > 1) ds.parts.forEach((p, i) => console.log('          ' + p.id.padEnd(8) + (100 * sizes[i] / p.data.length).toFixed(2).padStart(6) + '%'));
    out[id] = { format: 'compression-evolution-run', v: 2, dataset: id, files: rec.files, size: score, pct: +pct.toFixed(3), perFile: rec.perFile, gens: rec.gens, evals: rec.evals, minutes: rec.minutes, genome: rec.genome, families: rec.families || {}, pop: (rec.pop || []).slice(0, 8), series: rec.series, extinct: rec.extinct || {}, log: (rec.log || []).slice(-80) };
}
const js = '/* generated by bake_champions.js from training/*.json — runs recorded offline with\n   train_headless.js; every champion was re-verified on every whole file while baking */\nwindow.CE_CHAMPIONS = ' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(__dirname, 'champions.js'), js);
console.log('champions.js: ' + Object.keys(out).length + ' runs, ' + (js.length / 1024).toFixed(1) + ' KB');
